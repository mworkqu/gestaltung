-- ── 1. Columns + allowed values ─────────────────────────────────────────────
alter table public.parts add column if not exists store_category text;
alter table public.parts add column if not exists store_category_review boolean not null default false;

alter table public.parts drop constraint if exists parts_store_category_check;
alter table public.parts add constraint parts_store_category_check check (
  store_category is null or store_category in (
    'Boards and microcontrollers', 'Sensors', 'Modules', 'Chips and ICs', 'Power',
    'Motors and mechanical', 'Cables and connectors', 'Tools and accessories', '3D printing'
  )
);

comment on column public.parts.store_category is
  'Storefront category (one of nine, 0048). parts.category stays the supplier/source category.';
comment on column public.parts.store_category_review is
  'True when store_category fell back to Tools and accessories because the source category had no rule (0048).';

create index if not exists parts_store_category_idx on public.parts (store_category);

-- ── 2. Rule table ───────────────────────────────────────────────────────────
create table if not exists public.store_category_rules (
  source_category text primary key,
  store_category  text not null check (store_category in (
    'Boards and microcontrollers', 'Sensors', 'Modules', 'Chips and ICs', 'Power',
    'Motors and mechanical', 'Cables and connectors', 'Tools and accessories', '3D printing'
  )),
  updated_at      timestamptz not null default now()
);

alter table public.store_category_rules enable row level security;
grant select, insert, update, delete on public.store_category_rules to authenticated;

drop policy if exists store_category_rules_admin on public.store_category_rules;
create policy store_category_rules_admin on public.store_category_rules
  for all to authenticated
  using (public.is_super_admin())
  with check (public.is_super_admin());

-- ── 3. Trigger: new products get a store category from the rules ────────────
create or replace function public.parts_fill_store_category()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_rule text;
begin
  if new.store_category is null then
    select r.store_category into v_rule
      from public.store_category_rules r
     where r.source_category = btrim(coalesce(new.category, ''));
    new.store_category := coalesce(v_rule, 'Tools and accessories');
    new.store_category_review := v_rule is null;
  end if;
  return new;
end $$;

