-- ── 7. Report ───────────────────────────────────────────────────────────────
do $$
declare
  r record;
  v_review integer;
  v_gift boolean;
begin
  for r in
    select store_category,
           count(*) filter (where is_published and merged_into is null) as published,
           count(*) filter (where is_published and merged_into is null and lead_time_class is not null) as listed
      from public.parts
     group by store_category
     order by store_category
  loop
    raise notice '0048: % — % published / % listed', coalesce(r.store_category, '(none)'), r.published, r.listed;
  end loop;
  select count(*) into v_review from public.parts
   where store_category_review and is_published and merged_into is null;
  select is_published into v_gift from public.parts where sku = 'VLT-44331994546493';
  raise notice '0048 applied: % published products flagged for a store category check; gift card published = %',
    v_review, coalesce(v_gift::text, '(not found)');
end $$;

